-- CP-15: per-asset retraction cleanup results. One row per (retraction event, asset) with
-- the honest outcome -- SUCCESS / FAILED (with reason, retried via outbox) / NOT_APPLICABLE
-- (with reason, e.g. "no object-storage surface exists"). The executor also creates this
-- table lazily (CREATE TABLE IF NOT EXISTS); this migration makes it a first-class citizen
-- on real PostgreSQL databases.
CREATE TABLE tb_retraction_cleanup_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outbox_event_id VARCHAR(36) NOT NULL,
  receipt_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  asset_key VARCHAR(48) NOT NULL,
  outcome VARCHAR(24) NOT NULL,
  affected_count INT NOT NULL DEFAULT 0,
  detail VARCHAR(480),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_retraction_cleanup_event_asset UNIQUE (outbox_event_id, asset_key)
);
